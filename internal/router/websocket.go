package router

import (
	"context"
	"encoding/json"
	"net/http"
	"os"
	"path/filepath"
	"strings"
	"sync"
	"time"

	"github.com/coder/websocket"

	"github.com/ammonode/daemon/internal/server"
)

type wsMessage struct {
	Event string   `json:"event"`
	Args  []string `json:"args,omitempty"`
}

// websocket implements the console protocol (compatible with Pterodactyl's):
// the client must send {"event":"auth","args":[jwt]} first, then may send
// "send command", "set state", "send logs" and "send stats".
func (r *Router) websocket(w http.ResponseWriter, req *http.Request) {
	s, ok := r.manager.Get(req.PathValue("uuid"))
	if !ok {
		writeError(w, http.StatusNotFound, "server not found")
		return
	}
	origins := append([]string{strings.TrimPrefix(strings.TrimPrefix(strings.TrimRight(r.cfg.Remote, "/"), "https://"), "http://")}, r.cfg.API.TrustedOrigins...)
	conn, err := websocket.Accept(w, req, &websocket.AcceptOptions{OriginPatterns: origins})
	if err != nil {
		return
	}
	conn.SetReadLimit(32 * 1024)
	ctx, cancel := context.WithCancel(req.Context())
	defer cancel()
	defer conn.CloseNow()

	var (
		writeMu sync.Mutex
		claims  *WebsocketClaims
		claimMu sync.RWMutex
	)
	send := func(event string, args ...string) {
		b, _ := json.Marshal(wsMessage{Event: event, Args: args})
		writeMu.Lock()
		defer writeMu.Unlock()
		wctx, c := context.WithTimeout(ctx, 10*time.Second)
		defer c()
		_ = conn.Write(wctx, websocket.MessageText, b)
	}
	can := func(p string) bool {
		claimMu.RLock()
		defer claimMu.RUnlock()
		return claims != nil && claims.Can(p)
	}

	events := s.Events.Subscribe()
	defer s.Events.Unsubscribe(events)

	// Forward server events once authenticated; expire the session with the token.
	go func() {
		tick := time.NewTicker(10 * time.Second)
		defer tick.Stop()
		for {
			select {
			case <-ctx.Done():
				return
			case ev, ok := <-events:
				if !ok {
					return
				}
				if !can("websocket.connect") {
					continue
				}
				if (ev.Name == server.EventInstallOutput || ev.Name == server.EventInstallStarted) && !can("admin.websocket.install") && !can("*") {
					continue
				}
				send(ev.Name, ev.Args...)
			case <-tick.C:
				claimMu.RLock()
				expired := claims != nil && claims.ExpiresAt != nil && time.Until(claims.ExpiresAt.Time) < 0
				expiring := claims != nil && claims.ExpiresAt != nil && time.Until(claims.ExpiresAt.Time) < time.Minute
				claimMu.RUnlock()
				if expired {
					send("token expired")
					cancel()
					return
				}
				if expiring {
					send("token expiring")
				}
			}
		}
	}()

	for {
		_, data, err := conn.Read(ctx)
		if err != nil {
			return
		}
		var msg wsMessage
		if json.Unmarshal(data, &msg) != nil {
			continue
		}
		if msg.Event == "auth" {
			if len(msg.Args) == 0 {
				send("jwt error", "missing token")
				continue
			}
			c, err := parseToken(r.cfg.Token, msg.Args[0], &WebsocketClaims{})
			if err != nil || c.ServerUUID != s.ID() || !c.Can("websocket.connect") {
				send("jwt error", "invalid token")
				continue
			}
			claimMu.Lock()
			claims = c
			claimMu.Unlock()
			send("auth success")
			send(server.EventStatus, s.State())
			continue
		}
		if !can("websocket.connect") {
			send("jwt error", "not authenticated")
			continue
		}
		switch msg.Event {
		case "send logs":
			if s.IsInstalling() {
				for _, l := range s.Logs.Lines() {
					send(server.EventInstallOutput, l)
				}
				continue
			}
			for _, l := range s.Logs.Lines() {
				send(server.EventConsoleOutput, l)
			}
		case "send stats":
			b, _ := json.Marshal(s.Stats())
			send(server.EventStats, string(b))
		case "send command":
			if len(msg.Args) > 0 && can("control.console") {
				if err := s.SendCommand(msg.Args[0]); err != nil {
					send(server.EventDaemonMessage, err.Error())
				}
			}
		case "set state":
			if len(msg.Args) == 0 {
				continue
			}
			action := msg.Args[0]
			perm := map[string]string{"start": "control.start", "stop": "control.stop", "restart": "control.restart", "kill": "control.stop"}[action]
			if perm == "" || !can(perm) {
				send("daemon error", "permission denied")
				continue
			}
			go func() {
				if err := Power(s, action); err != nil {
					send(server.EventDaemonMessage, err.Error())
				}
			}()
		}
	}
}

// downloadFile streams a file using a one-time token generated by the panel.
func (r *Router) downloadFile(w http.ResponseWriter, req *http.Request) {
	c, err := parseToken(r.cfg.Token, req.URL.Query().Get("token"), &FileClaims{})
	if err != nil {
		writeError(w, http.StatusUnauthorized, err.Error())
		return
	}
	s, ok := r.manager.Get(c.ServerUUID)
	if !ok {
		writeError(w, http.StatusNotFound, "server not found")
		return
	}
	full, err := server.SafePath(s.Dir(), c.FilePath)
	if err != nil {
		writeError(w, http.StatusBadRequest, err.Error())
		return
	}
	f, err := os.Open(full)
	if err != nil {
		writeError(w, http.StatusNotFound, "file not found")
		return
	}
	defer f.Close()
	st, _ := f.Stat()
	if st.IsDir() {
		writeError(w, http.StatusBadRequest, "cannot download a directory")
		return
	}
	w.Header().Set("Content-Disposition", "attachment; filename=\""+strings.ReplaceAll(filepath.Base(full), "\"", "")+"\"")
	http.ServeContent(w, req, st.Name(), st.ModTime(), f)
}
